              </li>
              <li><b>修改应用配置</b>：打开应用配置弹窗编辑当前配置；弹窗内切换项目管理会自动加载对应项目的已有配置。改完保存后发布信息自动刷新。</li>
              <li><b>刷新|重置</b>：重新读取默认项目与环境配置。</li>
            </ul>
